# Synthetic assessor score modifiers (design assumptions for demo variety, not empirical estimates)
def modifier(arch: str, crit: dict) -> float:
    dim, safety = crit["qf_dimension"], crit["is_safety_critical"]
    if arch == "practical_strong_theory_weak" and dim in ("knowledge", "viva", "materials", "manuals"):
        return -1.4
    if arch == "practical_strong_theory_weak" and crit["criterion_id"].startswith("C08"):
        return -1.6
    if arch == "safety_gaps" and safety:
        return -2.2
    if arch == "industrial" and crit["criterion_id"].startswith(("C05", "C07")):
        return +0.4
    if arch == "domestic" and crit["criterion_id"].startswith("C04"):
        return +0.3
    return 0.0


