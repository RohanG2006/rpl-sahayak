def observation(code: str, final: int, rng_: random.Random) -> dict:
    _, crit = CRIT[code]
    suggested = final if rng_.random() < 0.72 else clip(final + rng_.choice([-1, 1]))
    observed = list(OBS_GOOD.get(code, ["Work area visible"]))[: 1 + (final >= 3)]
    missing = [OBS_MISSING[code]] if code in OBS_MISSING and final <= 3 else []
    concerns = ["Hands near open terminals without gloves — verify isolation"] if crit["is_safety_critical"] and final <= 1 else []
    indicators = ["Neat, consistent workmanship"] if final >= 3 else (["Work incomplete in the image"] if final <= 1 else [])
    return {"observed": observed, "potentially_missing": missing, "safety_concerns": concerns, "competency_indicators": indicators,
            "suggested_score": suggested, "suggested_score_reason": f"Visible evidence most closely matches anchor {suggested}: {crit['anchors'][str(suggested)]}",
            "confidence": round(rng_.uniform(0.62, 0.92), 2), "analysis_basis": "image"}


