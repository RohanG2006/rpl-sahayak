def clip(x: float) -> int:
    return max(0, min(4, round(x)))


def placeholder_images() -> dict[str, Path]:
    IMG.mkdir(parents=True, exist_ok=True)
    try:
        font = ImageFont.truetype("arial.ttf", 34)
        small = ImageFont.truetype("arial.ttf", 24)
    except OSError:
        font = small = ImageFont.load_default()
    out = {}
    for task_id, code, what in REQUIRED:
        im = Image.new("RGB", (960, 720), (226, 222, 212))
        d = ImageDraw.Draw(im)
        # simple schematic: a board with terminals and conductors (varies by task)
        d.rectangle([180, 160, 780, 560], outline=(40, 40, 40), width=6, fill=(244, 241, 234))
        for i in range(6):
            x = 240 + i * 95
            d.ellipse([x, 230, x + 34, 264], outline=(30, 30, 30), width=4)
            d.line([x + 17, 264, x + 17, 520], fill=[(185, 28, 28), (29, 78, 216), (21, 128, 61)][i % 3], width=7)
        for i in range(0, 960, 48):
            d.line([i, 0, i + 300, 720], fill=(215, 210, 198), width=2)
        d.rectangle([0, 0, 960, 70], fill=(22, 25, 29))
        d.text((24, 16), "SYNTHETIC EVIDENCE PLACEHOLDER — not a real photo", fill=(255, 254, 251), font=small)
        d.rectangle([0, 650, 960, 720], fill=(255, 246, 232))
        d.text((24, 664), f"{code} · {task_id} · {what[:48]}", fill=(22, 25, 29), font=small)
        d.text((200, 580), code, fill=(22, 25, 29), font=font)
        p = IMG / f"{code}.png"
        im.save(p, optimize=True)
        out[code] = p
    return out


