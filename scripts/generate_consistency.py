"""
Generate the SIMULATION/TEST dataset for the assessor-consistency demonstration.

    python scripts/generate_consistency.py

Output: data/demo/consistency_test_set.csv  (+ consistency_parameters.json)

Model (per case i, rubric criterion c, assessor a):
    ability_i      ~ Uniform(ABILITY_MIN, ABILITY_MAX)          case's underlying competence on the 0-4 scale
    T_ic           = clip(ability_i + N(0, CRITERION_SD), 0, 4) "true" criterion level
    severity_a     ~ N(0, SEVERITY_SD)                          assessor leniency (+) / strictness (-)
    baseline_aic   = round(clip(T_ic + severity_a + N(0, BASE_NOISE_SD), 0, 4))
    standard_aic   = round(clip(T_ic + K_SEVERITY*severity_a + N(0, STD_NOISE_SD), 0, 4))

K_SEVERITY < 1 and STD_NOISE_SD < BASE_NOISE_SD encode the HYPOTHESIS that criterion-specific anchors and a shared
evidence checklist reduce leniency bias and interpretation noise. Because these values are chosen here, any
improvement shown on the dashboard is a consequence of these assumptions — the dataset demonstrates the measurement
pipeline, it is NOT evidence of real-world improvement.
"""
import csv
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED = 2026
N_CASES = 20
ASSESSORS = ["A01", "A02", "A03", "A04", "A05"]
PARAMS = {
    "seed": SEED, "n_cases": N_CASES, "assessors": ASSESSORS,
    "ability_min": 1.2, "ability_max": 3.6, "criterion_sd": 0.6,
    "severity_sd": 0.5, "base_noise_sd": 0.7,
    "k_severity": 0.35, "std_noise_sd": 0.4,
}
LABEL = "# SIMULATION / TEST DATA — synthetic ratings generated by scripts/generate_consistency.py. NOT real assessor data. Improvement size is an input assumption."


def clip(x: float) -> float:
    return max(0.0, min(4.0, x))


def main() -> None:
    rng = random.Random(SEED)
    tasks = json.loads((ROOT / "data/assessment/electrician_tasks.json").read_text(encoding="utf-8"))["tasks"]
    criteria = [(t["task_id"], c["criterion_id"]) for t in tasks for c in t["criteria"]]
    severity = {a: round(rng.gauss(0, PARAMS["severity_sd"]), 3) for a in ASSESSORS}
    rows = []
    for i in range(1, N_CASES + 1):
        case = f"C{i:03d}"
        ability = rng.uniform(PARAMS["ability_min"], PARAMS["ability_max"])
        for task, crit in criteria:
            true = clip(ability + rng.gauss(0, PARAMS["criterion_sd"]))
            for a in ASSESSORS:
                b = round(clip(true + severity[a] + rng.gauss(0, PARAMS["base_noise_sd"])))
                s = round(clip(true + PARAMS["k_severity"] * severity[a] + rng.gauss(0, PARAMS["std_noise_sd"])))
                rows.append((case, task, crit, a, "baseline", b))
                rows.append((case, task, crit, a, "standardised", s))
    out = ROOT / "data/demo/consistency_test_set.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="", encoding="utf-8") as f:
        f.write(LABEL + "\n")
        f.write("# parameters: " + json.dumps(PARAMS) + "\n")
        w = csv.writer(f)
        w.writerow(["case_id", "task_code", "criterion_code", "assessor_id", "mode", "score", "data_origin"])
        for r in rows:
            w.writerow([*r, "simulation"])
    meta = {"label": LABEL.lstrip("# "), "parameters": PARAMS, "assessor_severity_drawn": severity, "rows": len(rows),
            "criteria": len(criteria), "generated_by": "scripts/generate_consistency.py"}
    (ROOT / "data/demo/consistency_parameters.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"{len(rows)} rows · {N_CASES} cases × {len(criteria)} criteria × {len(ASSESSORS)} assessors × 2 modes · severity {severity}")


if __name__ == "__main__":
    main()
